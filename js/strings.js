/** The language in use: the user's choice, or else the browser's ('pl' or 'en'). */
export function getLang() {
  const chosen = getState().settings.lang;
  if (chosen) return chosen;
  return (navigator.language || 'en').toLowerCase().startsWith('pl') ? 'pl' : 'en';
}

/** The locale handed to speech recognition: 'pl-PL' or 'en-US'. */
export function getSpeechLocale() {
  return getLang() === 'pl' ? 'pl-PL' : 'en-US'; // American English, always
}

/** Look up a string, filling {placeholders} from `vars`. */
export function t(key, vars = {}) {
  const template = STRINGS[getLang()][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}

/** Fill in every tagged element in the page. Safe to call again after a language change. */
export function applyStrings() {
  document.documentElement.lang = getLang();
  // on a touch screen, a hint that says "hover" or "click" has a touch twin
  const touch = matchMedia('(hover: none) and (pointer: coarse)').matches;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    el.textContent = t(touch && el.dataset.i18nTouch ? el.dataset.i18nTouch : el.dataset.i18n);
  }
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of document.querySelectorAll('[data-i18n-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  }
}

/** 45 → "45 min", 60 → "1 h", 90 → "1 h 30 min" (in the current language). */
export function formatMinutes(total) {
  const h = Math.floor(total / 60);
  const m = total % 60;
  if (!h) return t('minutesShort', { n: m });
  return m ? t('hoursMinutes', { h, m }) : t('hours', { h });
}
